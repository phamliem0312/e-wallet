import type { NextConfig } from "next";

const dev = process.env.NODE_ENV !== "production";

/**
 * Tiêu đề bảo mật (F-ACC-01.NFR-04). ponytail: script-src cho phép 'unsafe-inline' vì Next.js chèn script inline khi
 * hydrate; muốn bỏ thì chuyển sang CSP có nonce sinh trong middleware (buộc mọi trang render động).
 */
const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${dev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join("; ");

const nextConfig: NextConfig = {
  poweredByHeader: false,
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "Content-Security-Policy", value: csp },
          { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "same-origin" },
        ],
      },
    ];
  },
};

export default nextConfig;
